# Python Data Types

name = "Faria"          # String
age = 25                # Integer
height = 5.2            # Float
is_student = True       # Boolean
complex_num = 2 + 3j    # Complex

print("Name:", name)
print("Type:", type(name))

print("Age:", age)
print("Type:", type(age))

print("Height:", height)
print("Type:", type(height))

print("Student:", is_student)
print("Type:", type(is_student))

print("Complex Number:", complex_num)
print("Type:", type(complex_num))
